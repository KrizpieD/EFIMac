base = None
for line in raw.strip().splitlines():
    m = re.match(r'0x([0-9A-F]+):\s+((?:[0-9A-F]{8}\s*)+)', line)
    addr = int(m.group(1), 16)
    if base is None:
        base = addr
    for w in m.group(2).split():
        data += int(w, 16).to_bytes(4, 'big')

open(r'C:\Users\clayc\AppData\Local\Temp\opencode\helper.bin', 'wb').write(data)
print('base', hex(base), 'len', len(data))

md = Cs(CS_ARCH_PPC, CS_MODE_32 | CS_MODE_BIG_ENDIAN)
md.detail = True
for i in md.disasm(data, base):
    print("0x%08x  %-10s %s" % (i.address, i.mnemonic, i.op_str))
